#!/usr/bin/env node
/**
 * Import Eleventy starter projects from https://github.com/11ty/docs.
 *
 * Writes `config/11ty-starters.json`, which `config/sites.js` reads. Re-run it
 * whenever the upstream list changes; the file is generated, not hand-edited.
 *
 *   node scripts/import-11ty-starters.mjs
 *   STARTERS_REPO=owner/name node scripts/import-11ty-starters.mjs
 *
 * Each starter is one JSON file carrying a `url` (its repository) and usually a
 * `demo` (the deployed site). Only the demo is imported: a repository page is a
 * GitHub page, and measuring it would score GitHub rather than the starter.
 *
 * `excludedFromLeaderboards: true` is honoured. It is upstream saying this entry
 * should not be ranked, and importing it anyway would override the maintainers
 * of the list on their own data.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { normalizeUrl } from "../lib/hash.js";

const REPO = process.env.STARTERS_REPO || "11ty/docs";
const REF = process.env.STARTERS_REF || "main";
const DIR = process.env.STARTERS_DIR || "src/_data/starters";
const OUT = process.env.STARTERS_OUT || "config/11ty-starters.json";

/** Fetch the repository tarball; one request, no token, always cleaned up. */
function fetchTree() {
	const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "11ty-starters-"));
	const tarball = path.join(tmp, "repo.tar.gz");
	const url = `https://codeload.github.com/${REPO}/tar.gz/refs/heads/${REF}`;

	execFileSync("curl", ["-fsSL", "-o", tarball, url], { stdio: ["ignore", "ignore", "inherit"] });
	execFileSync("tar", ["-xzf", tarball, "-C", tmp], { stdio: ["ignore", "ignore", "inherit"] });

	const root = fs
		.readdirSync(tmp, { withFileTypes: true })
		.filter((e) => e.isDirectory())
		.map((e) => path.join(tmp, e.name))[0];

	if (!root) throw new Error(`Nothing extracted from ${url}`);
	return { tmp, entries: path.join(root, DIR) };
}

let tmp;
let entriesDir;

try {
	({ tmp, entries: entriesDir } = fetchTree());
} catch (error) {
	process.stderr.write(`\n  Could not fetch ${REPO}: ${error.message}\n\n`);
	process.exit(1);
}

if (!fs.existsSync(entriesDir)) {
	fs.rmSync(tmp, { recursive: true, force: true });
	process.stderr.write(`\n  ${REPO} has no ${DIR}/ directory — has its layout changed?\n\n`);
	process.exit(1);
}

const files = fs.readdirSync(entriesDir).filter((f) => f.endsWith(".json"));

const seen = new Set();
const starters = [];
const skipped = { excluded: 0, noDemo: 0, invalid: 0, duplicate: 0, nonHttp: 0, unreadable: 0 };

for (let file of files.sort()) {
	let entry;
	try {
		entry = JSON.parse(fs.readFileSync(path.join(entriesDir, file), "utf8"));
	} catch {
		skipped.unreadable++;
		continue;
	}

	// Upstream's own opt-out, honoured rather than second-guessed.
	if (entry?.excludedFromLeaderboards) {
		skipped.excluded++;
		continue;
	}

	// No demo means nothing deployed to measure — `url` is the repository.
	if (!entry?.demo || !String(entry.demo).trim()) {
		skipped.noDemo++;
		continue;
	}

	let url;
	try {
		url = new URL(String(entry.demo).trim());
	} catch {
		skipped.invalid++;
		continue;
	}

	if (url.protocol !== "http:" && url.protocol !== "https:") {
		skipped.nonHttp++;
		continue;
	}

	const normalized = normalizeUrl(url.toString());
	if (seen.has(normalized)) {
		skipped.duplicate++;
		continue;
	}

	seen.add(normalized);
	starters.push({ url: normalized, name: entry.name || file.replace(/\.json$/, "") });
}

fs.rmSync(tmp, { recursive: true, force: true });

if (!starters.length) {
	process.stderr.write(`\n  Found no usable demos in ${REPO}/${DIR} — refusing to write an empty list.\n\n`);
	process.exit(1);
}

starters.sort((a, b) => a.url.localeCompare(b.url));
const urls = starters.map((s) => s.url);

// Read the previous list before overwriting it — the only moment the comparison
// is possible, since this file is rewritten rather than merged.
const previous = fs.existsSync(OUT)
	? (() => {
			try {
				return new Set((JSON.parse(fs.readFileSync(OUT, "utf8")).urls || []).map(normalizeUrl));
			} catch {
				return null;
			}
		})()
	: null;

const current = new Set(urls);
const removed = previous ? [...previous].filter((u) => !current.has(u)).sort() : [];
const added = previous ? urls.filter((u) => !previous.has(u)) : [];

fs.mkdirSync(path.dirname(path.resolve(OUT)), { recursive: true });
fs.writeFileSync(
	OUT,
	JSON.stringify(
		{
			generated: new Date().toISOString(),
			source: `https://github.com/${REPO}/tree/${REF}/${DIR}`,
			note: "Generated by scripts/import-11ty-starters.mjs — do not edit by hand.",
			entries: files.length,
			starters,
			urls,
		},
		null,
		2,
	) + "\n",
);

const hosts = new Set(urls.map((u) => new URL(u).hostname));

process.stdout.write(
	`\n  wrote ${OUT}\n` +
		`  ${urls.length} demos across ${hosts.size} hosts, from ${files.length} starters\n` +
		`  skipped: ${skipped.excluded} excluded upstream, ${skipped.noDemo} with no demo, ` +
		`${skipped.duplicate} duplicate, ${skipped.invalid} unparseable, ${skipped.nonHttp} non-HTTP, ` +
		`${skipped.unreadable} unreadable\n` +
		(previous === null
			? `  no previous list to compare against\n`
			: `  changes: +${added.length} added, -${removed.length} removed\n`) +
		"\n",
);

if (removed.length) {
	process.stdout.write(`  REMOVED UPSTREAM — ${removed.length}\n`);
	for (let url of removed) process.stdout.write(`    ${url}\n`);
	process.stdout.write("\n");
}
if (added.length) {
	process.stdout.write(`  ADDED — ${added.length}\n`);
	for (let url of added.slice(0, 25)) process.stdout.write(`    ${url}\n`);
	if (added.length > 25) process.stdout.write(`    …and ${added.length - 25} more\n`);
	process.stdout.write("\n");
}
