#!/usr/bin/env node
/**
 * Import contact home pages from the address-book project.
 *
 * Writes `config/addressbook.json`, which `config/sites.js` reads. Re-run it
 * whenever the address book changes; the file is generated, not hand-edited.
 *
 *   node scripts/import-addressbook.mjs
 *   ADDRESSBOOK_DB=/path/to/data.db node scripts/import-addressbook.mjs
 *
 * **Only the homepage URL is imported.** Names, bios, notes, avatars and social
 * profiles all stay in the address book. These sites belong to real people and
 * the output of this project is a public web page — the URL is the only field
 * it needs, and the display name is derived from the URL anyway.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { normalizeUrl } from "../lib/hash.js";

const DB_PATH = process.env.ADDRESSBOOK_DB || path.join(os.homedir(), "Code/address-book/data.db");
const OUT = process.env.ADDRESSBOOK_OUT || "config/addressbook.json";

/**
 * Contacts carrying any of these tags are left out entirely.
 *
 * Matched case-insensitively, the same way the address book's own unique index
 * on tags does, so "problematic" and "Problematic" are one tag.
 *
 * Override with a comma-separated list:
 *   ADDRESSBOOK_EXCLUDE_TAGS="Problematic,Inactive" npm run import:addressbook
 */
const EXCLUDE_TAGS = (process.env.ADDRESSBOOK_EXCLUDE_TAGS ?? "Problematic,Brand")
	.split(",")
	.map((t) => t.trim())
	.filter(Boolean);

if (!fs.existsSync(DB_PATH)) {
	process.stderr.write(`No address book database at ${DB_PATH}\nSet ADDRESSBOOK_DB to point at it.\n`);
	process.exit(1);
}

// Read-only: this script must never be able to modify the address book.
const db = new DatabaseSync(DB_PATH, { readOnly: true });

// One placeholder per excluded tag, or a clause that matches nothing when the
// list is empty — simpler than branching on two different queries.
const tagPlaceholders = EXCLUDE_TAGS.length ? EXCLUDE_TAGS.map(() => "? COLLATE NOCASE").join(", ") : "NULL";

const rows = db
	.prepare(
		`SELECT homepage FROM contacts c
		 WHERE c.homepage IS NOT NULL AND TRIM(c.homepage) != ''
		   AND NOT EXISTS (
		     SELECT 1 FROM tags t
		     WHERE t.contact_id = c.id AND t.tag IN (${tagPlaceholders})
		   )
		 ORDER BY c.homepage COLLATE NOCASE`
	)
	.all(...EXCLUDE_TAGS);

// Counted separately so the run reports what it left out rather than silently
// producing a shorter list.
const excluded = EXCLUDE_TAGS.length
	? db
			.prepare(
				`SELECT COUNT(DISTINCT c.id) AS n FROM contacts c
				 JOIN tags t ON t.contact_id = c.id
				 WHERE c.homepage IS NOT NULL AND TRIM(c.homepage) != ''
				   AND t.tag IN (${tagPlaceholders})`
			)
			.get(...EXCLUDE_TAGS).n
	: 0;

db.close();

const seen = new Set();
const urls = [];
const skipped = { invalid: 0, duplicate: 0, nonHttp: 0 };

for (let { homepage } of rows) {
	let url;
	try {
		url = new URL(String(homepage).trim());
	} catch {
		skipped.invalid++;
		continue;
	}

	// A mailto: or ftp: entry is not something Lighthouse can measure.
	if (url.protocol !== "http:" && url.protocol !== "https:") {
		skipped.nonHttp++;
		continue;
	}

	const normalized = normalizeUrl(url.toString());

	// Two contacts can share a site. Measuring it twice would duplicate the
	// history and hit that person's server twice as often.
	if (seen.has(normalized)) {
		skipped.duplicate++;
		continue;
	}

	seen.add(normalized);
	urls.push(normalized);
}

fs.mkdirSync(path.dirname(path.resolve(OUT)), { recursive: true });
fs.writeFileSync(
	OUT,
	JSON.stringify(
		{
			generated: new Date().toISOString(),
			source: "address-book",
			note: "Generated by scripts/import-addressbook.mjs — do not edit by hand.",
			excludedTags: EXCLUDE_TAGS,
			excludedCount: excluded,
			urls,
		},
		null,
		2
	) + "\n"
);

const hosts = new Set(urls.map((u) => new URL(u).hostname));

process.stdout.write(
	`\n  wrote ${OUT}\n` +
		`  ${urls.length.toLocaleString()} URLs across ${hosts.size.toLocaleString()} hosts\n` +
		(excluded ? `  excluded ${excluded} tagged ${EXCLUDE_TAGS.map((t) => `"${t}"`).join(", ")}\n` : "") +
		`  skipped: ${skipped.duplicate} duplicate, ${skipped.invalid} unparseable, ${skipped.nonHttp} non-HTTP\n\n` +
		(excluded
			? `  Run \`node scripts/purge-excluded.mjs\` to delete any stored history\n  for excluded URLs.\n\n`
			: "")
);
